# โจทย์ข้อที่ 1: คำนวณคะแนนเฉลี่ย 3 วิชา
# Input: บรรทัดที่ 1-3 คะแนนวิชาที่ 1, 2, 3 (จำนวนเต็ม)
# Output: คะแนนเฉลี่ย
# ==========================================


# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
s1 = int(input("วิชาฟิสิกส์ : "))
s2 = int(input("วิชาเคมี : "))
s3 = int(input("วิชาชีววิทยา : "))
result = s1+s2+s3
total = result/3
print("คะแนนเฉลี่ย : ",+ total)
